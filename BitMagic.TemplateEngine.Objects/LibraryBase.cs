using System.ComponentModel;

namespace BitMagic.TemplateEngine.Objects;

public abstract class LibraryBase
{
    // class full name -> source file, set by the template engine before a build runs
    private static readonly Dictionary<string, string> _owners = new(StringComparer.Ordinal);

    // one instance of each library per build, initialised once
    private static readonly Dictionary<Type, LibraryBase> _instances = new();
    private static readonly HashSet<Type> _initialised = new();

    /// <summary>
    /// The library's source file.
    /// </summary>
    public string Owner => _owners.TryGetValue(GetType().FullName ?? "", out var owner) ? owner : GetType().FullName ?? "";

    public virtual void Initialise()
    {
        // Method that gets called at the start of the application, after the library's own imports.
    }

    /// <summary>
    /// Generated by the template engine: initialises the libraries this one imports.
    /// </summary>
    [EditorBrowsable(EditorBrowsableState.Never)]
    public virtual void InitialiseImports()
    {
    }

    /// <summary>
    /// The library's instance for this build.
    /// </summary>
    [EditorBrowsable(EditorBrowsableState.Never)]
    public static T Instance<T>() where T : LibraryBase, new()
    {
        if (!_instances.TryGetValue(typeof(T), out var instance))
        {
            instance = new T();
            _instances.Add(typeof(T), instance);
        }

        return (T)instance;
    }

    /// <summary>
    /// Initialises a library once per build: its imports first, then the library.
    /// </summary>
    [EditorBrowsable(EditorBrowsableState.Never)]
    public static void InitialiseLibrary(LibraryBase library)
    {
        if (!_initialised.Add(library.GetType()))
            return;

        library.InitialiseImports();
        library.Initialise();
    }

    /// <summary>
    /// Called by the template engine before a build runs, so each library knows its source file.
    /// </summary>
    [EditorBrowsable(EditorBrowsableState.Never)]
    public static void SetOwners(IEnumerable<KeyValuePair<string, string>> classToSourceFile)
    {
        _owners.Clear();

        foreach (var (className, sourceFile) in classToSourceFile)
            _owners[className] = sourceFile;
    }

    internal static void Reset()
    {
        _instances.Clear();
        _initialised.Clear();
    }
}
