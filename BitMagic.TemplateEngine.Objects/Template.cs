using System.Text;

namespace BitMagic.TemplateEngine.Objects;

public static class Template
{
    // the output is a tree: lines, plus anchors that hold lines written into them later
    internal static readonly List<CapturedItem> _output = new();
    private static readonly Stack<List<CapturedItem>> _targets = new();

    private static List<CapturedItem> Target => _targets.Count == 0 ? _output : _targets.Peek();

    public static void WriteLiteral(string literal, int lineNumber, string sourceFile)
    {
        if (literal.IndexOf('\n') != -1)    // if the literal is multiple lines, then dont map as we can't
        {
            var lines = literal.Split('\n');

            foreach (var l in lines)
            {
                Target.Add(new CapturedLine(l, 0, ""));
            }

            return;
        }

        Target.Add(new CapturedLine(literal, string.IsNullOrWhiteSpace(sourceFile) ? -1 : lineNumber, sourceFile));
    }

    /// <summary>
    /// Marks the current position in the output. Anything written to the anchor later, with
    /// <see cref="WriteTo(Anchor)"/>, appears here.
    /// </summary>
    public static Anchor Anchor()
    {
        var anchor = new Anchor();
        Target.Add(new CapturedAnchor(anchor));
        return anchor;
    }

    /// <summary>
    /// Sends the output to the anchor until the result is disposed.
    /// </summary>
    public static IDisposable WriteTo(Anchor anchor)
    {
        _targets.Push(anchor.Items);
        return new PopTarget(anchor.Items);
    }

    /// <summary>
    /// Runs body, collecting what it writes rather than adding it to the output.
    /// </summary>
    public static IReadOnlyList<CapturedItem> Capture(Action body)
    {
        var captured = new List<CapturedItem>();

        using (new PopTarget(captured, push: true))
            body();

        return captured;
    }

    /// <summary>
    /// Writes captured items to the output, keeping their source map.
    /// </summary>
    public static void Write(IEnumerable<CapturedItem> items) => Target.AddRange(items);

    /// <summary>
    /// A keyword a view claims, eg 'section code'. Generated by the template engine; it's
    /// only valid inside <see cref="Capture(Action)"/>, where the view handles it.
    /// </summary>
    public static void Keyword(string keyword, string arguments, int lineNumber, string sourceFile) =>
        Target.Add(new KeywordLine(keyword, arguments, lineNumber, sourceFile));

    public static void StartProject()
    {
        _output.Clear();
        _targets.Clear();
        Build.Reset();
        Section.Reset();
        LibraryBase.Reset();
    }

    public static ISourceResult GenerateCode()
    {
        var code = new StringBuilder();
        var map = new List<ISourceResultMap>();
        var written = new HashSet<Anchor>();

        Flatten(_output, code, map, written);

        Section.CheckWritten(written);

        return new SourceResult(code.ToString(), map.ToArray());
    }

    private static void Flatten(List<CapturedItem> items, StringBuilder code, List<ISourceResultMap> map, HashSet<Anchor> written)
    {
        foreach (var item in items)
        {
            switch (item)
            {
                case CapturedLine line:
                    code.AppendLine(line.Text);
                    map.Add(new SourceResultMap(line.Line, line.SourceFile));
                    break;

                case CapturedAnchor anchor:
                    if (!written.Add(anchor.Anchor))
                        throw new TemplateSourceException(null, -1, "The same anchor is written to the output twice, so its code would be duplicated.");

                    Flatten(anchor.Anchor.Items, code, map, written);
                    break;

                case KeywordLine keyword:
                    throw new TemplateSourceException(keyword.SourceFile, keyword.Line, $"'{keyword.Keyword}' can only be used in a file whose view handles it.");
            }
        }
    }

    private sealed class PopTarget : IDisposable
    {
        private readonly List<CapturedItem> _target;
        private bool _disposed;

        public PopTarget(List<CapturedItem> target, bool push = false)
        {
            _target = target;

            if (push)
                _targets.Push(target);
        }

        public void Dispose()
        {
            if (_disposed)
                return;

            _disposed = true;

            if (_targets.Count == 0 || _targets.Peek() != _target)
                throw new InvalidOperationException("Template output targets were ended out of order.");

            _targets.Pop();
        }
    }
}

/// <summary>
/// A spot in the output, filled in later with <see cref="Template.WriteTo(Anchor)"/>.
/// </summary>
public sealed class Anchor
{
    internal List<CapturedItem> Items { get; } = new();
}

/// <summary>
/// What <see cref="Template.Capture(Action)"/> returns: output lines, keywords for a view to
/// handle, and anchors placed while capturing.
/// </summary>
public abstract record class CapturedItem(int Line, string SourceFile);
public sealed record class CapturedLine(string Text, int Line, string SourceFile) : CapturedItem(Line, SourceFile);
public sealed record class KeywordLine(string Keyword, string Arguments, int Line, string SourceFile) : CapturedItem(Line, SourceFile);
public sealed record class CapturedAnchor(Anchor Anchor) : CapturedItem(-1, "");

/// <summary>
/// An error at a line of a source file. The template engine reports it against that file
/// and line. Line is zero based, like the source map.
/// </summary>
public class TemplateSourceException(string? sourceFile, int line, string message) : Exception(message)
{
    public string? SourceFile { get; } = sourceFile;
    public int Line { get; } = line;
}

/// <summary>
/// An error a view reports at a line of the file it's viewing.
/// </summary>
public sealed class ViewException(CapturedItem at, string message) : TemplateSourceException(at.SourceFile, at.Line, message);
